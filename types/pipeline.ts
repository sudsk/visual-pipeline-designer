// ============================================================================
// AI Types
// ============================================================================

export interface AIAnalysis {
  architecture: ArchitectureRecommendation;
  dataVault: DataVaultStructure;
  optimizations: Optimization[];
  dqRules: DQRule[];
}

export interface ArchitectureRecommendation {
  layers: {
    bronze: string[];
    silver: string[];
    gold: string[];
  };
  rationale: string;
  complexity: 'simple' | 'moderate' | 'complex';
  estimatedEffort: string;
}

export interface Optimization {
  type: 'performance' | 'cost' | 'quality';
  title: string;
  description: string;
  impact: 'high' | 'medium' | 'low';
  estimatedSavings?: string;
  implementation?: string;
}

// ============================================================================
// Mapping Import Types
// ============================================================================

export interface MappingSpec {
  sourceTables: SourceTable[];
  transformations: MappingTransformation[];
  targetStructure: TargetStructure;
}

export interface SourceTable {
  schema: string;
  table: string;
  columns: ColumnMapping[];
}

export interface ColumnMapping {
  sourceColumn: string;
  sourceType: string;
  targetColumn?: string;
  targetType?: string;
  transformation?: string;
  businessKey?: boolean;
}

export interface MappingTransformation {
  name: string;
  sourceColumns: string[];
  logic: string;
  targetColumn: string;
}

export interface TargetStructure {
  type: 'data_vault' | 'dimensional' | 'flat';
  tables: TargetTable[];
}

export interface TargetTable {
  name: string;
  type: 'hub' | 'link' | 'satellite' | 'fact' | 'dimension';
  columns: TargetColumn[];
}

export interface TargetColumn {
  name: string;
  type: string;
  nullable: boolean;
  description?: string;
}

// ============================================================================
// Environment Types
// ============================================================================

export interface EnvironmentConfig {
  environment: 'dev' | 'uat' | 'prod';
  readOnly: boolean;
  features: {
    visualDesigner: boolean;
    codeGeneration: boolean;
    deployment: boolean;
    aiAssistant: boolean;
  };
  deployment: {
    type: 'cloud_run' | 'gke';
    serviceName: string;
    authentication: 'iap' | 'oauth' | 'none';
    authorizedUsers?: string[];
  };
  bigquery: {
    project: string;
    dataset?: string;
    location: string;
  };
  dataform: {
    repository: string;
    branch: string;
  };
}

